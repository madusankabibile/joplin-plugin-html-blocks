const ROWS = 5;
const UNKNOWN = ['...', '...', '...', '...', '...'];

/** How wide a banner may get before the rest of the line is dropped. */
const MAX_CHARS = 40;

/**
 * Turns one line of text into the five rows of ASCII art that spell it out.
 * Returns an empty array for an empty line.
 */
export const bannerLines = (text: string): string[] => {
	const chars = String(text).trim().toUpperCase().slice(0, MAX_CHARS).split('');
	if (!chars.length) return [];

	const rows: string[] = [];

	for (let row = 0; row < ROWS; row++) {
		const parts = chars.map(char => {
			const glyph = GLYPHS[char] || UNKNOWN;
			return glyph[row].replace(/\./g, ' ').replace(/#/g, '█');
		});
		rows.push(parts.join(' ').replace(/\s+$/, ''));
	}

	// A line of only spaces and unknown characters draws nothing at all.
	return rows.some(row => row.trim() !== '') ? rows : [];
};
